def search_hospital_knowledge(query: str) -> dict:
    """Retrieves matching hospital or kiosk knowledge snippets based on keywords."""
    q_low = query.lower()
    snippets = []
    
    if any(k in q_low for k in ["kiosk", "machine", "scan", "screen", "swasthya sync", "interview"]):
        snippets.append({
            "topic": "SwasthyaSync Smart Kiosk",
            "info": KIOSK_KNOWLEDGE["purpose"],
            "details": KIOSK_KNOWLEDGE["features"]
        })
    
    matched_depts = []
    for dept in HOSPITAL_DEPARTMENTS:
        if dept["name"].lower() in q_low or any(k in q_low for k in dept["description"].lower().split()):
            matched_depts.append(dept)
    
    if matched_depts:
        snippets.append({
            "topic": "Departments",
            "matches": matched_depts
        })
    elif any(k in q_low for k in ["department", "doctor", "specialist", "room"]):
        snippets.append({
            "topic": "All Available Departments",
            "departments": [d["name"] + " (" + d["room"] + ")" for d in HOSPITAL_DEPARTMENTS]
        })
        
    for faq in HOSPITAL_FAQS:
        if any(w in faq["question"].lower() for w in q_low.split() if len(w) > 3):
            snippets.append({"faq_question": faq["question"], "faq_answer": faq["answer"]})
            
    return {
        "hospital": HOSPITAL_PROFILE,
        "results": snippets
    }
